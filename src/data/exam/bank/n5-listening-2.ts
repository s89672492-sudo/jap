import type { ExamQuestion, ScriptLine, ScriptSpeaker } from '../types';

/**
 * N5 聽解擴充題第 2 組（模擬考第 3～5 回用；依 JLPT 題型自編的原創練習題，非官方試題）。
 * 目前用手機內建語音播放（沒有音檔）；發話表現沒有插圖，改用文字說明情境。
 * 課題理解、重點理解：script 第一句是情境說明，sentence 是問題（播放時前後各唸一次）。
 * 發話表現：sentence 是情境和問題，三個說法用唸的。即時應答：script 是一句話，三個回答用唸的。
 */
const BASE = { license: 'original', version: 1 } as const;

type Line = [ScriptSpeaker, string];
const lines = (items: Line[]): ScriptLine[] => items.map(([speaker, text]) => ({ speaker, text }));

function dialogue(
  id: string,
  subcategory: 'task' | 'point',
  difficulty: 1 | 2 | 3,
  script: Line[],
  sentence: string,
  options: [string, string, string, string],
  explanation: string,
  translation: string,
  optionNotes: [string, string, string, string],
): ExamQuestion {
  return {
    ...BASE,
    id,
    type: 'listening',
    subcategory,
    difficulty,
    script: lines(script),
    sentence,
    options,
    explanation,
    translation,
    optionNotes,
  };
}

function utterance(
  id: string,
  difficulty: 1 | 2 | 3,
  sentence: string,
  options: [string, string, string],
  explanation: string,
  translation: string,
  optionNotes: [string, string, string],
): ExamQuestion {
  return {
    ...BASE,
    id,
    type: 'listening',
    subcategory: 'utterance',
    difficulty,
    sentence,
    options,
    explanation,
    translation,
    optionNotes,
  };
}

function quick(
  id: string,
  difficulty: 1 | 2 | 3,
  speaker: ScriptSpeaker,
  line: string,
  options: [string, string, string],
  explanation: string,
  translation: string,
  optionNotes: [string, string, string],
): ExamQuestion {
  return {
    ...BASE,
    id,
    type: 'listening',
    subcategory: 'quick-response',
    difficulty,
    script: lines([[speaker, line]]),
    sentence: 'いちばん いい へんじを えらんで ください。',
    options,
    explanation,
    translation,
    optionNotes,
  };
}

