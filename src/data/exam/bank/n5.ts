type Choice = [
  options: [string, string, string, string],
  explanation: string,
  notes: [string, string, string, string],
];

/** 文章文法：一篇文章挖 4 個空格，每個空格一題 */
function textGrammar(
  idPrefix: string,
  groupId: string,
  difficulty: 1 | 2 | 3,
  blanks: Choice[],
): ExamQuestion[] {
  const numbers = ['１', '２', '３', '４'];
  return blanks.map(([options, explanation, optionNotes], i) => ({
    ...BASE,
    id: `${idPrefix}-${i + 1}`,
    type: 'text-grammar',
    subcategory: 'text-grammar',
    difficulty,
    groupId,
    sentence: `（${numbers[i]}）に [入|はい]る ものは どれですか。`,
    options,
    explanation,
    translation: `第 ${i + 1} 個空格應該填入哪一個？`,
    optionNotes,
  }));
}

/** 讀解題：文章在題組裡 */
function reading(
  id: string,
  groupId: string,
  subcategory: 'short' | 'mid' | 'info-search',
  difficulty: 1 | 2 | 3,
  q: {
    sentence: string;
    options: [string, string, string, string];
    explanation: string;
    optionNotes: [string, string, string, string];
  },
): ExamQuestion {
  return { ...BASE, id, type: 'reading', subcategory, difficulty, groupId, ...q };
}
