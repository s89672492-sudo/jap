import type { ExamQuestion } from '../types';

/**
 * N4 擴充題庫（依 JLPT 題型自編的原創練習題，非官方試題）。
 * 句子和文章可以直接寫注音 [漢字|かな]；選項不加注音。
 * optionNotes 的順序和 options 一樣，第一個是正確答案。
 * 讀解、文章文法的文章放在 groups/n4.ts（groupId）。
 */
const BASE = { license: 'original', version: 1 } as const;

type Four = [string, string, string, string];

function paraphrase(
  id: string,
  difficulty: 1 | 2 | 3,
  sentence: string,
  options: Four,
  explanation: string,
  translation: string,
  optionNotes: Four,
): ExamQuestion {
  return {
    ...BASE,
    id,
    type: 'paraphrase',
    subcategory: 'paraphrase',
    difficulty,
    sentence,
    options,
    explanation,
    translation,
    optionNotes,
  };
}

/** 用法：題目是一個詞，選出用法正確的句子 */
function usage(
  id: string,
  difficulty: 1 | 2 | 3,
  word: string,
  meaning: string,
  options: Four,
  explanation: string,
  optionNotes: Four,
): ExamQuestion {
  return {
    ...BASE,
    id,
    type: 'usage',
    subcategory: 'usage',
    difficulty,
    sentence: word,
    options,
    explanation,
    translation: `「${word}」：${meaning}`,
    optionNotes,
  };
}

function order(
  id: string,
  difficulty: 1 | 2 | 3,
  sentence: string,
  options: Four,
  explanation: string,
  translation: string,
  optionNotes: Four,
): ExamQuestion {
  return {
    ...BASE,
    id,
    type: 'sentence-order',
    subcategory: 'sentence-order',
    difficulty,
    sentence,
    options,
    explanation,
    translation,
    optionNotes,
  };
}

type Choice = [options: Four, explanation: string, notes: Four];

/** 文章文法：一篇文章挖 4 個空格，每個空格一題 */
function textGrammar(
  idPrefix: string,
  groupId: string,
  difficulty: 1 | 2 | 3,
  blanks: Choice[],
): ExamQuestion[] {
  const numbers = ['１', '２', '３', '４'];
  return blanks.map(([options, explanation, optionNotes], i) => ({
    ...BASE,
    id: `${idPrefix}-${i + 1}`,
    type: 'text-grammar',
    subcategory: 'text-grammar',
    difficulty,
    groupId,
    sentence: `（${numbers[i]}）に [入|はい]る ものは どれですか。`,
    options,
    explanation,
    translation: `第 ${i + 1} 個空格應該填入哪一個？`,
    optionNotes,
  }));
}

/** 讀解題：文章在題組裡 */
function reading(
  id: string,
  groupId: string,
  subcategory: 'short' | 'mid' | 'info-search',
  difficulty: 1 | 2 | 3,
  sentence: string,
  options: Four,
  explanation: string,
  optionNotes: Four,
): ExamQuestion {
  return {
    ...BASE,
    id,
    type: 'reading',
    subcategory,
    difficulty,
    groupId,
    sentence,
    options,
    explanation,
    optionNotes,
  };
}

