/**
 * 固定考卷：模擬考第 1〜5 回。同一回、同一版本的題目和選項順序每次都一樣，方便重考比較。
 * 題目內容改了（題庫修正）就要加一個新版本，舊版本保留不刪（舊紀錄另存考卷快照）。
 * contentHash 是題目內容的檢查碼，npm run check:data 會比對，內容變了卻沒換版本就會報錯。
 * 題目全部是依 JLPT 題型自編的原創練習題，不是官方歷屆試題。
 */
export type ExamPaperVersion = {
  version: number;
  /** 題目 id（照出題順序；分節由藍圖決定） */
  questionIds: string[];
  contentHash: string;
  note?: string;
};

export type ExamPaperDef = {
  id: string;
  level: JlptLevel;
  /** 第幾回 */
  number: number;
  title: string;
  versions: ExamPaperVersion[];
};

